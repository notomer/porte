"""Component B: application-specialized code generation.

The optimizer is deliberately narrow. It consumes facts that only execution
can supply (observed value window, host-transition accounting) and emits a
module whose fast paths are guarded by exactly those facts and whose slow
paths are the untouched generic module. The transform catalogue is small on
purpose: the research contribution under test is the admission pipeline -
guards, differential proof, cache - not the individual peephole.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from . import build, util

PORTE_VERSION = "0.1.0"


@dataclass
class Plan:
    transform: str
    version: int
    kernel: str
    facts: dict
    assumptions: list[str]
    params: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "transform": self.transform,
            "version": self.version,
            "kernel": self.kernel,
            "facts": self.facts,
            "assumptions": self.assumptions,
            "params": self.params,
            "porte_version": PORTE_VERSION,
        }


def plan_from_profiles(profiles: dict[str, dict]) -> list[Plan]:
    """Turn observed facts into candidate specializations.

    A candidate is emitted only when the observation is strong enough to be
    worth guarding: a narrow value window relative to n for the rank kernel,
    and per-record host transitions for the audit kernel.
    """
    plans: list[Plan] = []

    rank = profiles.get("rank_small_range") or {}
    facts = (rank.get("facts") or {}).get("rank")
    if facts:
        n = facts["n"]
        span = facts["span"]
        if facts["observations"] >= 1 and span <= max(64, n // 8):
            plans.append(Plan(
                transform="rank-counting",
                version=1,
                kernel="rank",
                facts={"min": facts["min"], "max": facts["max"],
                       "span": span, "n": n,
                       "observations": facts["observations"]},
                assumptions=[
                    f"every value lies in [{facts['min']},{facts['max']}]",
                    f"observed value span {span} is narrow relative to n={n}",
                    "n >= 1024",
                    "the sorted permutation is the only use of the input; "
                    "queries and checksum come from the shared contract",
                ],
                params={"window": span},
            ))

    audit = profiles.get("audit_basic") or {}
    ta = audit.get("transition_accounting") or {}
    b = audit.get("boundary") or {}
    ept = ta.get("entries_per_transition")
    if ta.get("host_transitions") and ept and ept >= 1 and b.get("flags") == 0:
        plans.append(Plan(
            transform="host-batch",
            version=1,
            kernel="audit",
            facts={"transitions": ta["host_transitions"],
                   "entries": ta["host_entries"],
                   "entries_per_transition": ept},
            assumptions=[
                "the host advertises batch entry points at run time",
                "no observer reads the ledger between kernel entry and exit "
                "(params[1] == 0)",
                "the externally observable effect is the ordered sequence of "
                "ledger entries, not the number of host transitions",
            ],
            params={"batch": 128},
        ))
    return plans


_HEADER = """\
/* Generated by Porte {porte}. Do not edit.
 * transforms: {names}
 * observed:   {facts}
 * assumptions:
{assumptions}
 */
#include "kernel_contract.h"
#include "host.h"

#include <stdint.h>
#include <stdlib.h>

#define API __attribute__((visibility("default")))
#define PORTE_TRANSFORM "{names}"

extern int64_t porte_kernel_rank_generic(const int32_t *, const int32_t *,
                                         int64_t, int32_t *, int64_t);
extern int64_t porte_kernel_audit_generic(const int32_t *, const int32_t *,
                                          int64_t, int32_t *);
extern int host_has_batch(void);

static int64_t g_fast_calls;
static int64_t g_fallback_calls;
"""


def _footer(plans: list[Plan]) -> str:
    kernels = {p.kernel for p in plans}
    caps = 0
    if "rank" in kernels:
        caps |= 1
    if "audit" in kernels:
        caps |= 2
    out = []
    if "rank" not in kernels:
        out.append("""
API int64_t porte_kernel_rank(const int32_t *params, const int32_t *vals,
                              int64_t n, int32_t *out, int64_t q) {
    return porte_kernel_rank_generic(params, vals, n, out, q);
}
""")
    if "audit" not in kernels:
        out.append("""
API int64_t porte_kernel_audit(const int32_t *params, const int32_t *recs,
                               int64_t n, int32_t *out) {
    return porte_kernel_audit_generic(params, recs, n, out);
}
""")
    out.append(f"""
API const char *porte_kernel_impl(void) {{ return "porte:" PORTE_TRANSFORM; }}
API uint64_t porte_kernel_caps(void) {{ return {caps}; }}
API int64_t porte_kernel_counters(int which) {{
    return which == 0 ? g_fast_calls : which == 1 ? g_fallback_calls : 0;
}}
""")
    return "".join(out)


def _emit_rank(plan: Plan) -> str:
    lo = int(plan.facts["min"])
    hi = int(plan.facts["max"])
    span = int(plan.facts["span"])
    return f"""
#define RANK_OBS_LO {lo}
#define RANK_OBS_HI {hi}
#define RANK_SPAN_MAX {span}
#define RANK_N_MIN 1024

/* Fast path: counting sort inside the observed window.
 * Guard cost is one streaming min/max pass. On failure the generic module
 * runs unchanged, so a wrong assumption costs time, never results. */
API int64_t porte_kernel_rank(const int32_t *params, const int32_t *vals,
                              int64_t n, int32_t *out, int64_t q) {{
    if (n < RANK_N_MIN || q < 0) {{
        g_fallback_calls++;
        return porte_kernel_rank_generic(params, vals, n, out, q);
    }}
    int32_t lo = INT32_MAX, hi = INT32_MIN;
    for (int64_t i = 0; i < n; i++) {{
        int32_t v = vals[i];
        lo = v < lo ? v : lo;
        hi = v > hi ? v : hi;
    }}
    int64_t s = (int64_t)hi - (int64_t)lo + 1;
    if (lo < RANK_OBS_LO || hi > RANK_OBS_HI || s > RANK_SPAN_MAX) {{
        g_fallback_calls++;
        return porte_kernel_rank_generic(params, vals, n, out, q);
    }}
    uint32_t *count = (uint32_t *)calloc((size_t)s, sizeof(uint32_t));
    int32_t *scratch = (int32_t *)malloc((size_t)n * sizeof(int32_t));
    if (!count || !scratch) {{
        free(count);
        free(scratch);
        g_fallback_calls++;
        return porte_kernel_rank_generic(params, vals, n, out, q);
    }}
    for (int64_t i = 0; i < n; i++) count[(uint32_t)(vals[i] - lo)]++;
    uint32_t running = 0;
    for (int64_t c = 0; c < s; c++) {{
        uint32_t t = count[c];
        count[c] = running;
        running += t;
    }}
    for (int64_t i = 0; i < n; i++)
        scratch[count[(uint32_t)(vals[i] - lo)]++] = vals[i];

    int64_t r = porte_rank_result(scratch, n, params, out, q);
    free(count);
    free(scratch);
    g_fast_calls++;
    return r;
}}
"""


def _emit_audit(plan: Plan) -> str:
    batch = int(plan.params.get("batch", 128))
    return f"""
#define AUDIT_BATCH {batch}
#define AUDIT_N_MIN {batch * 4}

/* Fast path: identical effect sequence, one host transition per batch.
 * Guarded by a host capability report and the caller's promise that nothing
 * observes the ledger mid-kernel; both are recorded as assumptions. */
API int64_t porte_kernel_audit(const int32_t *params, const int32_t *recs,
                               int64_t n, int32_t *out) {{
    if (params[1] != 0 || n < AUDIT_N_MIN || !host_has_batch()) {{
        g_fallback_calls++;
        return porte_kernel_audit_generic(params, recs, n, out);
    }}
    const int32_t strict = 0; /* guarded above: params[1] == 0 */
    host_entry entries[AUDIT_BATCH];
    uint64_t acc = 0;
    int64_t i = 0;
    while (i < n) {{
        int64_t k = 0;
        for (; k < AUDIT_BATCH && i < n; k++, i++) {{
            int32_t v = recs[i];
            int32_t key = porte_audit_key(v);
            int32_t val = porte_audit_val(v, strict);
            entries[k].tag = 0x41554449;
            entries[k].key = key;
            entries[k].val = val;
            entries[k].pad = 0;
            out[i] = val;
            acc += (uint64_t)(uint32_t)key;
        }}
        host_emit_batch(entries, k);
    }}
    g_fast_calls++;
    return (int64_t)acc;
}}
"""


def emit_c(plans: list[Plan], out_c: Path) -> Path:
    if not plans:
        raise ValueError("no plans to emit")
    names = "+".join(f"{p.transform}-v{p.version}" for p in plans)
    assumptions = "\n".join(f" *   - {a}" for p in plans for a in p.assumptions)
    facts = {p.kernel: p.facts for p in plans}
    header = _HEADER.format(porte=PORTE_VERSION, names=names,
                            facts=facts, assumptions=assumptions)
    body = []
    for p in plans:
        body.append(_emit_rank(p) if p.kernel == "rank" else _emit_audit(p))
    source = header + "".join(body) + _footer(plans)
    util.ensure_dir(out_c.parent)
    out_c.write_text(source)
    return out_c


def compile_plans(plans: list[Plan], arch: str, out_dir: Path) -> dict:
    """Emit and compile a plan set; returns artifact metadata."""
    util.ensure_dir(out_dir)
    c_path = emit_c(plans, out_dir / "generated.c")
    lib_path = out_dir / f"libporte_kernel_spec_{arch}.dylib"
    p = build.paths_for(arch)
    build.build_specialization(c_path, lib_path, arch, p["generic"])
    names = "+".join(f"{p.transform}-v{p.version}" for p in plans)
    return {
        "dir": str(out_dir),
        "source": str(c_path),
        "dylib": str(lib_path),
        "source_sha256": util.sha256_file(c_path),
        "dylib_sha256": util.sha256_file(lib_path),
        "plan": {
            "transform": names,
            "version": max(p.version for p in plans),
            "porte_version": PORTE_VERSION,
            "plans": [p.to_dict() for p in plans],
        },
        "assumptions": [a for p in plans for a in p.assumptions],
    }
