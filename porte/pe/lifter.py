"""Trace lifter: x86-64 instructions -> C with explicit x86 semantics.

This is not a decompiler and not a general recompiler. It translates one
discovered loop, instruction by instruction, into a C function whose
observable effects are the x86-64 register file, the arithmetic flags, and
memory. Instructions outside the supported set make the candidate ineligible;
nothing is guessed and nothing is looked up by name.

The generated function is compiled for ARM64 by clang. Every memory access is
bounds-checked against the regions handed in by the dispatcher, and a failed
check returns to the emulator at the exact instruction that failed, with all
prior effects applied. That is the deoptimization path.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field

from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_OP_REG

GPR_ALIASES: dict[str, tuple[int, int]] = {}
_GPR64 = ["rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi",
          "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15"]
_GPR32 = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi",
          "r8d", "r9d", "r10d", "r11d", "r12d", "r13d", "r14d", "r15d"]
_GPR16 = ["ax", "cx", "dx", "bx", "sp", "bp", "si", "di",
          "r8w", "r9w", "r10w", "r11w", "r12w", "r13w", "r14w", "r15w"]
_GPR8 = ["al", "cl", "dl", "bl", "spl", "bpl", "sil", "dil",
         "r8b", "r9b", "r10b", "r11b", "r12b", "r13b", "r14b", "r15b"]
for _names, _width in ((_GPR64, 8), (_GPR32, 4), (_GPR16, 2), (_GPR8, 1)):
    for _idx, _n in enumerate(_names):
        GPR_ALIASES[_n] = (_idx, _width)

MASK64 = (1 << 64) - 1

CONDITIONS = {
    "je": "zf", "jz": "zf", "jne": "!zf", "jnz": "!zf",
    "jb": "cf", "jc": "cf", "jnae": "cf",
    "jae": "!cf", "jnb": "!cf", "jnc": "!cf",
    "jbe": "cf || zf", "jna": "cf || zf",
    "ja": "!cf && !zf", "jnbe": "!cf && !zf",
    "js": "sf", "jns": "!sf", "jo": "of", "jno": "!of",
    "jp": "pf", "jpe": "pf", "jnp": "!pf", "jpo": "!pf",
    "jl": "sf != of", "jnge": "sf != of",
    "jge": "sf == of", "jnl": "sf == of",
    "jle": "zf || (sf != of)", "jng": "zf || (sf != of)",
    "jg": "!zf && (sf == of)", "jnle": "!zf && (sf == of)",
}

PRELUDE = """\
/* Generated by Porte's opaque-PE trace lifter. Do not edit. */
#include <stdint.h>
#include <string.h>

typedef struct {
    uint64_t gpr[16];
    uint64_t rip;
    uint64_t rflags;
} PorteCpu;

typedef struct {
    uint8_t *host;
    uint64_t guest;
    uint64_t size;
} PorteRegion;

typedef struct {
    PorteRegion region[4];
    uint64_t count;
} PorteMem;

static inline uint64_t porte_parity(uint8_t v) {
    v ^= (uint8_t)(v >> 4);
    v ^= (uint8_t)(v >> 2);
    v ^= (uint8_t)(v >> 1);
    return (uint64_t)((~v) & 1);
}

static inline uint64_t porte_pack(uint64_t cf, uint64_t pf, uint64_t af,
                                  uint64_t zf, uint64_t sf, uint64_t of) {
    return 0x202ull | (cf & 1) | ((pf & 1) << 2) | ((af & 1) << 4) |
           ((zf & 1) << 6) | ((sf & 1) << 7) | ((of & 1) << 11);
}

static inline __attribute__((unused)) int porte_find(const PorteMem *m, uint64_t addr, uint64_t n,
                             uint8_t **out) {
    for (uint64_t i = 0; i < m->count; i++) {
        const PorteRegion *r = &m->region[i];
        if (addr >= r->guest && addr + n <= r->guest + r->size) {
            *out = r->host + (addr - r->guest);
            return 1;
        }
    }
    return 0;
}

static inline __attribute__((unused)) int porte_load(const PorteMem *m, uint64_t addr, uint64_t n,
                             uint64_t *out) {
    uint8_t *p = 0;
    if (!porte_find(m, addr, n, &p)) return 0;
    uint64_t v = 0;
    memcpy(&v, p, (size_t)n);
    *out = v;
    return 1;
}

static inline __attribute__((unused)) int porte_store(const PorteMem *m, uint64_t addr, uint64_t n,
                              uint64_t v) {
    uint8_t *p = 0;
    if (!porte_find(m, addr, n, &p)) return 0;
    memcpy(p, &v, (size_t)n);
    return 1;
}

/* Fixed-width access through an already bounds-checked host pointer. */
static inline uint64_t porte_ld(const uint8_t *p, uint64_t n) {
    uint64_t v = 0;
    switch (n) {
        case 1: v = *(const uint8_t *)p; break;
        case 2: memcpy(&v, p, 2); break;
        case 4: memcpy(&v, p, 4); break;
        case 8: memcpy(&v, p, 8); break;
        default: memcpy(&v, p, (size_t)n); break;
    }
    return v;
}

static inline void porte_st(uint8_t *p, uint64_t n, uint64_t v) {
    switch (n) {
        case 1: *(uint8_t *)p = (uint8_t)v; break;
        case 2: memcpy(p, &v, 2); break;
        case 4: memcpy(p, &v, 4); break;
        case 8: memcpy(p, &v, 8); break;
        default: memcpy(p, &v, (size_t)n); break;
    }
}
"""


class UnsupportedInstruction(RuntimeError):
    pass


@dataclass
class TraceSource:
    c_source: str
    instructions: int
    labels: list[int] = field(default_factory=list)
    memory_ops: int = 0
    branches: int = 0
    pinned_sites: int = 0
    sha256: str = ""


class Emitter:
    def __init__(self, head: int, end: int, mutate: str | None = None,
                 pinned: dict[int, int] | None = None):
        self.head = head
        self.end = end
        self.mutate = mutate
        self.pinned = pinned or {}
        self.lines: list[str] = []
        self.ntmp = 0
        self.memory_ops = 0
        self.branches = 0
        self.perturbed = False
        self.pins_used: set[int] = set()

    def emit(self, line: str) -> None:
        self.lines.append("    " + line)

    def tmp(self) -> str:
        self.ntmp += 1
        return f"f{self.ntmp}"

    # ---- register helpers -------------------------------------------
    def alias(self, insn, reg_id: int) -> tuple[int, int]:
        name = insn.reg_name(reg_id)
        if name not in GPR_ALIASES:
            raise UnsupportedInstruction(f"register {name} is not supported")
        return GPR_ALIASES[name]

    def read_reg(self, idx: int, width: int) -> str:
        if width == 8:
            return f"r{idx}"
        return f"((uint64_t)(uint{width * 8}_t)r{idx})"

    def write_reg(self, idx: int, width: int, expr: str) -> None:
        if width == 8:
            self.emit(f"r{idx} = ({expr});")
        elif width == 4:
            self.emit(f"r{idx} = (uint64_t)(uint32_t)({expr});")
        elif width == 2:
            self.emit(f"r{idx} = (r{idx} & ~0xFFFFull) | (uint64_t)(uint16_t)({expr});")
        elif width == 1:
            self.emit(f"r{idx} = (r{idx} & ~0xFFull) | (uint64_t)(uint8_t)({expr});")
        else:
            raise UnsupportedInstruction(f"register width {width}")

    def ea(self, insn, op) -> str:
        mem = op.mem
        if mem.base:
            base_name = insn.reg_name(mem.base)
            if base_name in ("rip", "eip"):
                target = (insn.address + insn.size + mem.disp) & MASK64
                return f"0x{target:x}ull"
            idx, _ = self.alias(insn, mem.base)
            terms = [f"r{idx}"]
        else:
            terms = []
        if mem.index:
            idx, _ = self.alias(insn, mem.index)
            terms.append(f"(r{idx} * {mem.scale})")
        if mem.disp:
            terms.append(f"({mem.disp})" if mem.disp < 0 else f"{mem.disp}")
        return " + ".join(terms) if terms else "0"

    def pin_guard(self, insn, addr: str, width: int) -> str | None:
        """Direct host access for a site the profile pinned to one region.

        The guard is a two-compare range check against that region. It is a
        genuine guard, not an assumption: a miss returns to the emulator at
        the faulting instruction, so the general path is always reachable.
        """
        k = self.pinned.get(insn.address)
        if k is None or k > 3:
            return None
        self.pins_used.add(k)
        return (f"(addr >= g{k} && addr - g{k} <= s{k} - {width}u)")

    def load_operand(self, insn, op, width: int | None = None) -> str:
        if op.type == X86_OP_IMM:
            return f"0x{op.imm & MASK64:x}ull"
        if op.type == X86_OP_REG:
            idx, w = self.alias(insn, op.reg)
            return self.read_reg(idx, w)
        if op.type == X86_OP_MEM:
            size = width or op.size
            addr = self.ea(insn, op)
            t = self.tmp()
            guard = self.pin_guard(insn, addr, size)
            if guard is not None:
                k = self.pinned[insn.address]
                a = self.tmp()
                self.emit(f"uint64_t {a} = {addr};")
                self.emit(f"if (!({a} >= g{k} && {a} - g{k} <= s{k} - {size}u)) "
                          f"BAIL(0x{insn.address:x}ull);")
                self.emit(f"uint64_t {t} = porte_ld(h{k} + ({a} - g{k}), {size});")
            else:
                self.emit(f"uint64_t {t} = 0;")
                self.emit(f"if (!porte_load(mem, {addr}, {size}, &{t})) "
                          f"BAIL(0x{insn.address:x}ull);")
            self.memory_ops += 1
            if self.mutate == "perturb_load" and not self.perturbed:
                # Deliberate fault injection for the oracle's own self-test:
                # one loaded value is corrupted, nothing else changes.
                self.perturbed = True
                self.emit(f"{t} ^= 1ull;")
            return t
        raise UnsupportedInstruction("operand type")

    def store_operand(self, insn, op, width: int, value: str) -> None:
        if op.type == X86_OP_REG:
            idx, w = self.alias(insn, op.reg)
            self.write_reg(idx, w, value)
            return
        if op.type == X86_OP_MEM:
            addr = self.ea(insn, op)
            guard = self.pin_guard(insn, addr, width)
            if guard is not None:
                k = self.pinned[insn.address]
                a = self.tmp()
                self.emit(f"uint64_t {a} = {addr};")
                self.emit(f"if (!({a} >= g{k} && {a} - g{k} <= s{k} - {width}u)) "
                          f"BAIL(0x{insn.address:x}ull);")
                self.emit(f"porte_st(h{k} + ({a} - g{k}), {width}, {value});")
            else:
                self.emit(f"if (!porte_store(mem, {addr}, {width}, {value})) "
                          f"BAIL(0x{insn.address:x}ull);")
            self.memory_ops += 1
            return
        raise UnsupportedInstruction("destination must be register or memory")

    # ---- flags -------------------------------------------------------
    def flags_add(self, a: str, b: str, res: str, width: int) -> None:
        bits = width * 8
        mask = (1 << bits) - 1
        self.emit(f"cf = (({a}) < ({b}));")
        self.emit(f"zf = ((({res}) & 0x{mask:x}ull) == 0);")
        self.emit(f"sf = (({res}) >> {bits - 1}) & 1;")
        self.emit(f"of = (((({a}) ^ ({res})) & (({b}) ^ ({res}))) >> {bits - 1}) & 1;")
        self.emit(f"af = ((({a}) ^ ({b}) ^ ({res})) >> 4) & 1;")
        self.emit(f"pf = porte_parity((uint8_t)({res}));")

    def flags_sub(self, a: str, b: str, res: str, width: int) -> None:
        bits = width * 8
        mask = (1 << bits) - 1
        self.emit(f"cf = (({a}) < ({b}));")
        self.emit(f"zf = ((({res}) & 0x{mask:x}ull) == 0);")
        self.emit(f"sf = (({res}) >> {bits - 1}) & 1;")
        self.emit(f"of = (((({a}) ^ ({b})) & (({a}) ^ ({res}))) >> {bits - 1}) & 1;")
        self.emit(f"af = ((({a}) ^ ({b}) ^ ({res})) >> 4) & 1;")
        self.emit(f"pf = porte_parity((uint8_t)({res}));")

    def flags_logic(self, res: str, width: int) -> None:
        bits = width * 8
        mask = (1 << bits) - 1
        self.emit("cf = 0;")
        self.emit("of = 0;")
        self.emit(f"zf = ((({res}) & 0x{mask:x}ull) == 0);")
        self.emit(f"sf = (({res}) >> {bits - 1}) & 1;")
        self.emit(f"pf = porte_parity((uint8_t)({res}));")


def _jump_target(insn) -> int | None:
    for op in insn.operands:
        if op.type == X86_OP_IMM:
            return int(op.imm) & MASK64
    return None


def _operand_width(insn, op) -> int:
    if op.type == X86_OP_REG:
        _, w = GPR_ALIASES[insn.reg_name(op.reg)]
        return w
    if op.type == X86_OP_MEM:
        return getattr(op, "size", 0) or 8
    return getattr(op, "size", 0) or 8


def translate(insns: list, head: int, end: int, mutate: str | None = None,
              pinned: dict[int, int] | None = None,
              block_starts: list[int] | None = None) -> TraceSource:
    """Translate one natural loop (a set of basic blocks) into ARM64-targeted C.

    Control flow is emitted per edge: a branch whose target is another block of
    the loop becomes a label jump; anything leaving the loop stores the
    architectural state, sets RIP to the exit address and returns to the
    emulator. A block whose fall-through leaves the loop does the same.
    """
    em = Emitter(head, end, mutate=mutate, pinned=pinned)
    body = set(block_starts or [insns[0].address])
    labels = {i.address for i in insns}
    for insn in insns:
        if insn.mnemonic.startswith("j"):
            target = _jump_target(insn)
            if target is None:
                continue
            if (target not in body and target not in labels
                    and insn.mnemonic == "jmp"):
                continue
            if target in labels and target not in body:
                raise UnsupportedInstruction(
                    f"branch target 0x{target:x} leaves the loop")
            if target not in labels and target not in body:
                continue

    def exit_to(addr: int, prefix: str = "") -> None:
        em.emit(f"{prefix}{{ STORE(); cpu->rip = 0x{addr:x}ull; return 0; }}")

    # The dispatcher enters at the loop head. A natural loop may also contain
    # blocks that precede the head in address order (preheaders); without this
    # jump the trace would begin in the wrong place.
    em.emit(f"goto L_{head:x};")
    prev = None
    for insn in insns:
        m = insn.mnemonic
        ops = insn.operands
        if (prev is not None and not prev.mnemonic.startswith("j")
                and prev.mnemonic not in ("call", "ret", "retq")
                and prev.address + prev.size not in labels):
            # The previous block falls out of the loop. Execution reaches this
            # point only by falling through, so the exit belongs here.
            em.emit("STORE();")
            em.emit(f"cpu->rip = 0x{prev.address + prev.size:x}ull;")
            em.emit("return 0;")
        em.emit(f"L_{insn.address:x}: ;")
        if insn.address == head:
            em.emit("(*iters)++;")
        if m in ("nop", "endbr64", "pause"):
            continue
        if m.startswith("j") or m in ("call", "ret", "retq"):
            if m == "jmp":
                target = _jump_target(insn)
                em.branches += 1
                if target is not None and target in body:
                    em.emit(f"goto L_{target:x};")
                elif target is not None:
                    em.emit("STORE();")
                    em.emit(f"cpu->rip = 0x{target:x}ull;")
                    em.emit("return 0;")
                else:
                    raise UnsupportedInstruction("indirect jump inside the loop")
                continue
            if m in ("call", "ret", "retq"):
                raise UnsupportedInstruction(f"{m} inside the trace")
            if m not in CONDITIONS:
                raise UnsupportedInstruction(f"conditional branch {m}")
            target = _jump_target(insn)
            em.branches += 1
            cond = CONDITIONS[m]
            if target is not None and target in body:
                em.emit(f"if ({cond}) goto L_{target:x};")
            else:
                em.emit(f"if ({cond}) {{ STORE(); cpu->rip = 0x{target:x}ull; "
                        f"return 0; }}")
            fall = insn.address + insn.size
            if fall not in labels:
                # The not-taken edge leaves the loop: it must be a real exit.
                em.emit("STORE();")
                em.emit(f"cpu->rip = 0x{fall:x}ull;")
                em.emit("return 0;")
            continue

        if m == "mov":
            dst, src = ops
            if dst.type == X86_OP_REG:
                _, w = em.alias(insn, dst.reg)
            else:
                w = _operand_width(insn, dst)
            val = em.load_operand(insn, src, width=w)
            em.store_operand(insn, dst, w, val)
            continue

        if m == "mov":
            dst, src = ops
            if dst.type == X86_OP_REG:
                _, w = em.alias(insn, dst.reg)
            else:
                w = _operand_width(insn, dst)
            val = em.load_operand(insn, src, width=w)
            em.store_operand(insn, dst, w, val)
            continue

        if m in ("movzx", "movsx", "movsxd"):
            dst, src = ops
            _, dw = em.alias(insn, dst.reg)
            _, sw = em.alias(insn, src.reg) if src.type == X86_OP_REG else (0, src.size)
            if src.type == X86_OP_MEM:
                sw = getattr(src, "size", 0) or 8
            val = em.load_operand(insn, src, width=sw)
            if m == "movzx":
                res = f"(({val}) & 0x{(1 << (sw * 8)) - 1:x}ull)"
            elif m == "movsxd":
                res = f"((uint64_t)(int64_t)(int32_t)({val}))"
            else:
                cast = {1: "int8_t", 2: "int16_t", 4: "int32_t", 8: "int64_t"}[sw]
                res = f"((uint64_t)(int64_t)({cast})({val}))"
            em.write_reg(GPR_ALIASES[insn.reg_name(dst.reg)][0], dw, res)
            continue

        if m == "lea":
            dst, src = ops
            idx, dw = em.alias(insn, dst.reg)
            em.write_reg(idx, dw, em.ea(insn, src))
            continue

        if m in ("add", "sub", "and", "or", "xor"):
            dst, src = ops
            w = _operand_width(insn, dst)
            a = em.load_operand(insn, dst, width=w)
            b = em.load_operand(insn, src, width=w)
            ta = em.tmp(); tb = em.tmp(); res = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {tb} = {b};")
            opstr = {"add": "+", "sub": "-", "and": "&", "or": "|", "xor": "^"}[m]
            em.emit(f"uint64_t {res} = {ta} {opstr} {tb};")
            em.store_operand(insn, dst, w, res)
            if m == "add":
                em.flags_add(ta, tb, res, w)
            elif m == "sub":
                em.flags_sub(ta, tb, res, w)
            else:
                em.flags_logic(res, w)
            continue

        if m in ("cmp", "test"):
            a_op, b_op = ops
            w = _operand_width(insn, a_op)
            a = em.load_operand(insn, a_op, width=w)
            b = em.load_operand(insn, b_op, width=w)
            ta = em.tmp(); tb = em.tmp(); res = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {tb} = {b};")
            opstr = "-" if m == "cmp" else "&"
            em.emit(f"uint64_t {res} = {ta} {opstr} {tb};")
            if m == "cmp":
                em.flags_sub(ta, tb, res, w)
            else:
                em.flags_logic(res, w)
            continue

        if m in ("inc", "dec"):
            dst = ops[0]
            w = _operand_width(insn, dst)
            a = em.load_operand(insn, dst, width=w)
            ta = em.tmp(); res = em.tmp(); saved = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {saved} = cf;")
            sign = "+" if m == "inc" else "-"
            em.emit(f"uint64_t {res} = {ta} {sign} 1;")
            em.store_operand(insn, dst, w, res)
            if m == "inc":
                em.flags_add(ta, "1", res, w)
            else:
                em.flags_sub(ta, "1", res, w)
            em.emit(f"cf = {saved};")
            continue

        if m == "neg":
            dst = ops[0]
            w = _operand_width(insn, dst)
            a = em.load_operand(insn, dst, width=w)
            ta = em.tmp(); res = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {res} = (uint64_t)0 - {ta};")
            em.store_operand(insn, dst, w, res)
            em.flags_sub("0", ta, res, w)
            em.emit(f"cf = ({ta} != 0);")
            continue

        if m == "not":
            dst = ops[0]
            w = _operand_width(insn, dst)
            a = em.load_operand(insn, dst, width=w)
            res = em.tmp()
            em.emit(f"uint64_t {res} = ~({a});")
            em.store_operand(insn, dst, w, res)
            continue

        if m == "imul":
            if len(ops) == 1:
                raise UnsupportedInstruction("one-operand imul is not supported")
            dst = ops[0]
            idx, w = em.alias(insn, dst.reg)
            if len(ops) == 3:
                a = em.load_operand(insn, ops[1], width=w)
                imm = int(ops[2].imm)
                if mutate == "imul_imm":
                    imm += 1
                b = f"0x{imm & MASK64:x}ull"
            else:
                a = em.read_reg(idx, w)
                b = em.load_operand(insn, ops[1], width=w)
            ta = em.tmp(); tb = em.tmp(); res = em.tmp()
            prod = f"p_{insn.address:x}"
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {tb} = {b};")
            if w == 4:
                em.emit(f"int64_t {prod} = (int64_t)(int32_t){ta} * (int64_t)(int32_t){tb};")
                em.emit(f"uint64_t {res} = (uint32_t){prod};")
                em.emit(f"cf = of = ({prod} != (int64_t)(int32_t){res});")
            else:
                em.emit(f"__int128 {prod} = (__int128)(int64_t){ta} * (__int128)(int64_t){tb};")
                em.emit(f"uint64_t {res} = (uint64_t){prod};")
                em.emit(f"cf = of = ({prod} != (__int128)(int64_t){res});")
            em.write_reg(idx, w, res)
            continue

        if m in ("rol", "ror"):
            dst, cnt = ops
            w = _operand_width(insn, dst)
            bits = w * 8
            a = em.load_operand(insn, dst, width=w)
            if cnt.type == X86_OP_IMM:
                cnt_expr = f"{int(cnt.imm)}ull"
            else:
                idx, _ = em.alias(insn, cnt.reg)
                cnt_expr = f"((uint64_t)(uint8_t)r{idx})"
            ta = em.tmp(); tc = em.tmp(); res = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {tc} = ({cnt_expr}) & {bits - 1};")
            em.emit(f"uint64_t {res} = ({ta} & 0x{(1 << bits) - 1:x}ull);")
            if m == "rol":
                em.emit(f"{res} = {tc} ? ((({res} << {tc}) | ({res} >> ({bits} - {tc}))) "
                        f"& 0x{(1 << bits) - 1:x}ull) : {res};")
                em.emit(f"cf = {tc} ? ({res} & 1) : cf;")
                em.emit(f"of = {tc} ? ((({res} >> {bits - 1}) & 1) ^ cf) : of;")
            else:
                em.emit(f"{res} = {tc} ? ((({res} >> {tc}) | ({res} << ({bits} - {tc}))) "
                        f"& 0x{(1 << bits) - 1:x}ull) : {res};")
                em.emit(f"cf = {tc} ? (({res} >> {bits - 1}) & 1) : cf;")
                em.emit(f"of = {tc} ? ((({res} >> {bits - 1}) & 1) ^ (({res} >> {bits - 2}) & 1)) : of;")
            em.store_operand(insn, dst, w, res)
            continue

        if m in ("shl", "sal", "shr", "sar"):
            dst, cnt = ops
            w = _operand_width(insn, dst)
            bits = w * 8
            a = em.load_operand(insn, dst, width=w)
            if cnt.type == X86_OP_IMM:
                cnt_expr = f"{int(cnt.imm)}ull"
            else:
                idx, _ = em.alias(insn, cnt.reg)
                cnt_expr = f"((uint64_t)(uint8_t)r{idx})"
            ta = em.tmp(); tc = em.tmp(); res = em.tmp()
            em.emit(f"uint64_t {ta} = {a};")
            em.emit(f"uint64_t {tc} = ({cnt_expr}) & {bits - 1};")
            if m in ("shl", "sal"):
                em.emit(f"uint64_t {res} = (uint64_t)(({ta} << {tc}) & 0x{(1 << bits) - 1:x}ull);")
                em.emit(f"cf = {tc} ? (({ta} >> ({bits} - {tc})) & 1) : cf;")
                em.emit(f"of = ({tc} == 1) ? ((({res} >> {bits - 1}) & 1) ^ cf) : of;")
            elif m == "shr":
                em.emit(f"uint64_t {res} = ({ta} & 0x{(1 << bits) - 1:x}ull) >> {tc};")
                em.emit(f"cf = {tc} ? (({ta} >> ({tc} - 1)) & 1) : cf;")
                em.emit(f"of = ({tc} == 1) ? (({ta} >> {bits - 1}) & 1) : of;")
            else:
                if w == 4:
                    em.emit(f"uint64_t {res} = (uint32_t)((int32_t)({ta}) >> {tc});")
                else:
                    em.emit(f"uint64_t {res} = (uint64_t)((int64_t)({ta}) >> {tc});")
                em.emit(f"cf = {tc} ? (({ta} >> ({tc} - 1)) & 1) : cf;")
                em.emit(f"of = ({tc} == 1) ? 0 : of;")
            em.store_operand(insn, dst, w, res)
            em.emit(f"zf = (({res} & 0x{(1 << bits) - 1:x}ull) == 0);")
            em.emit(f"sf = ({res} >> {bits - 1}) & 1;")
            em.emit(f"pf = porte_parity((uint8_t){res});")
            continue

        if m == "cdqe":
            em.emit("r0 = (uint64_t)(int64_t)(int32_t)r0;")
            continue

        if m == "cwde":
            em.emit("r0 = (r0 & ~0xFFFFFFFFull) | (uint64_t)(uint32_t)(int32_t)(int16_t)r0;")
            continue

        if m in ("push", "pop"):
            raise UnsupportedInstruction("stack traffic inside the trace is not supported")

        raise UnsupportedInstruction(f"instruction {m!r} is not supported")

    if (prev is not None and not prev.mnemonic.startswith("j")
            and prev.mnemonic not in ("call", "ret", "retq")
            and prev.address + prev.size not in labels):
        em.emit("STORE();")
        em.emit(f"cpu->rip = 0x{prev.address + prev.size:x}ull;")
        em.emit("return 0;")

    body = "\n".join(em.lines)
    pins = sorted(em.pins_used)
    pin_decl = ""
    for k in pins:
        pin_decl += (f"    if (mem->count <= {k}) return 2;\n"
                     f"    uint8_t *h{k} = (uint8_t *)mem->region[{k}].host;\n"
                     f"    uint64_t g{k} = mem->region[{k}].guest, "
                     f"s{k} = mem->region[{k}].size;\n")
    store = " ".join(f"cpu->gpr[{i}] = r{i};" for i in range(16))
    store += " cpu->rflags = porte_pack(cf, pf, af, zf, sf, of);"
    guard = f"    if (!cpu || !mem || !iters) return 2;\n"
    source = PRELUDE + f"""
uint64_t porte_trace(PorteCpu *cpu, PorteMem *mem, uint64_t *iters) {{
{guard}{pin_decl}    uint64_t r0 = cpu->gpr[0], r1 = cpu->gpr[1], r2 = cpu->gpr[2], r3 = cpu->gpr[3],
             r4 = cpu->gpr[4], r5 = cpu->gpr[5], r6 = cpu->gpr[6], r7 = cpu->gpr[7],
             r8 = cpu->gpr[8], r9 = cpu->gpr[9], r10 = cpu->gpr[10], r11 = cpu->gpr[11],
             r12 = cpu->gpr[12], r13 = cpu->gpr[13], r14 = cpu->gpr[14], r15 = cpu->gpr[15];
    uint64_t cf = cpu->rflags & 1, pf = (cpu->rflags >> 2) & 1, af = (cpu->rflags >> 4) & 1,
             zf = (cpu->rflags >> 6) & 1, sf = (cpu->rflags >> 7) & 1,
             of = (cpu->rflags >> 11) & 1;
#define STORE() do {{ {store} }} while (0)
#define BAIL(A) do {{ cpu->rip = (A); STORE(); return 1; }} while (0)
{body}
}}
"""
    return TraceSource(
        c_source=source,
        instructions=len(insns),
        pinned_sites=len(pins),
        labels=sorted(labels),
        memory_ops=em.memory_ops,
        branches=em.branches,
        sha256=hashlib.sha256(source.encode()).hexdigest())
